#include "libft.h"

/**
 * @brief Outputs the character ’c’ to the specified file descriptor.
 * 
 * @param c The character to output
 * @param fd The file descriptor on which to write.
 */
void	ft_putchar_fd(char c, int fd)
{
	if (fd < 0)
		return ;
	write(fd, &c, 1);
}
